def prereg_logs(texts):
    """Logs that pre-register something: 'prereg' in the name, or a heading saying pre-registered."""
    return [n for n, t in texts.items() if not n.startswith(("DAILY", "INDEX")) and (
        "prereg" in n or re.search(r"^#+ .*[Pp]re-registered", t, re.M))]


def prereg_rows(root, entries, texts, files):
    """Each PREREG row with its commits, results and checks resolved."""
    by_title = {f["n"]: f for f in entries}
    added = added_files(root)
    fcommits = heading_commits(root)
    history = findings_history(root)

    def result_commit(n, checks):
        """The first commit whose entry F<n> holds every verdict string the entry holds now (a heading can come
        first as a placeholder); the heading's commit when it holds none of them."""
        now = norm(by_title[n]["body"]) if n in by_title else ""
        want = [norm(s) for s in checks if norm(s) in now]
        if want:
            for h, d, ents in history:
                if all(w in ents.get(n, "") for w in want):
                    return (h, d)
            return ("uncommitted",)
        return fcommits.get(n) or ("uncommitted",)
    rows = []
    for p in PREREG:
        r = dict(p)
        fixed, checks_missing = [], []
        rule_text = ""
        if p.get("rule_log"):
            rel = f"{SESSIONS_REL}/{p['rule_log']}"
            if (root / rel).exists():
                rule_text = (root / rel).read_text()
                c = added.get(rel)
                fixed.append(("log " + p["rule_log"][:15], c or ("uncommitted",)))
            else:
                fixed.append(("log " + p["rule_log"][:15], ("not found",)))
        if p.get("rule_commit"):
            c = commit_info(root, p["rule_commit"])
            fixed.append(("commit", c or (p["rule_commit"] + " (not in this history)",)))
            if c:
                rule_text += " " + c[2]
                if p.get("rule_file"):
                    rule_text += " " + git(root, "show", f"{p['rule_commit']}:{p['rule_file']}")
        if p.get("rule_pickaxe"):
            rel, s = p["rule_pickaxe"]
            c = pickaxe(root, rel, s)
            fixed.append((f"{rel} (\"{s}\")", c or ("not found",)))
            rule_text += " " + s if c else ""
        if p.get("rule_added"):
            c = added_files(root, p["rule_added"]).get(p["rule_added"])
            fixed.append((p["rule_added"].split("/")[-1] + " first committed", c or ("not found",)))
        for label, h in p.get("rule_extra", []):
            c = commit_info(root, h)
            fixed.append((label, c or (h + " (not in this history)",)))
        nrule = norm(rule_text)
        checks_missing += [f"rule source lacks \"{s}\"" for s in p.get("rule_check", []) if norm(s) not in nrule]
        fs = list(p.get("f", []))
        if p.get("f_title"):
            fs += [f["n"] for f in entries if re.search(p["f_title"], f["title"]) and f["n"] not in fs]
        res_logs = sorted({n for g in p.get("result_glob", []) for n in texts if fnmatch.fnmatch(n, g)})
        res_text = norm(" ".join([by_title[n]["body"] for n in fs if n in by_title] + [texts[n] for n in res_logs]))
        results = [(f"F{n}", result_commit(n, p.get("verdict_check", []))) for n in fs] + \
                  [("log " + n[:15], added.get(f"{SESSIONS_REL}/{n}") or ("uncommitted",)) for n in res_logs]
        waiting = not fs and not res_logs
        checks_missing += [f"results lack \"{s}\"" for s in p.get("verdict_check", []) if norm(s) not in res_text] \
            if not waiting else []
        dates_fixed = [parse_date(c[1]) for _, c in fixed if len(c) > 1]
        dates_res = [parse_date(c[1]) for _, c in results if len(c) > 1]
        first_fixed = min((d for d in dates_fixed if d), default=None)
        first_res = min((d for d in dates_res if d), default=None)
        order = ("waiting" if waiting else "n/a" if p["kind"] in ("exploratory", "none") or not first_fixed
                 or not first_res else "yes" if first_fixed <= first_res
                 else "NO: no fixing commit before the first result")
        run_note = None              # the entry's own run time against the rule's commit, to the minute
        if p["kind"] == "pre" and first_fixed:
            for n in fs:
                m = re.search(r"(?:Oct (\d{1,2}),? )?(\d{1,2}):(\d{2}) ?- ?(?:Oct \d{1,2},? )?\d{1,2}:\d{2}",
                              norm(by_title[n]["body"]) if n in by_title else "")
                if not m:
                    continue
                day = int(m.group(1)) if m.group(1) else (first_res or first_fixed).day
                start = first_fixed.replace(day=day, hour=int(m.group(2)), minute=int(m.group(3)), second=0)
                if first_fixed.replace(second=0) >= start:
                    same = first_fixed.replace(second=0) == start
                    run_note = (f"F{n} gives the run as starting {m.group(0).split('-')[0].strip()}; the earliest "
                                f"commit that fixed the rule is {first_fixed.strftime('%H:%M:%S')}: "
                                + ("the same minute, so git alone can't order the commit and the first call (the log "
                                   "says it was committed before any call)" if same else
                                   "AFTER the run's stated start"))
                break
        late = []                    # a log whose name says a later time than the commit that added it
        for label, c in fixed:
            m = re.match(r"log (\d{4}-\d{2}-\d{2})_(\d{2})(\d{2})", label)
            if m and len(c) > 1 and parse_date(c[1]):
                named = datetime.strptime(f"{m.group(1)} {m.group(2)}:{m.group(3)}", "%Y-%m-%d %H:%M")
                lag = (named - parse_date(c[1]).replace(tzinfo=None)).total_seconds() / 60
                if lag > 10:
                    late.append(f"the log's name says {m.group(2)}:{m.group(3)}, {lag:.0f} minutes after the commit "
                                f"that added it ({c[1][11:16]})")
        r.update(fixed=fixed, results=results, waiting=waiting, checked="yes" if not checks_missing else
                 "unverified: " + "; ".join(checks_missing), before=order, f_numbers=fs, result_logs=res_logs,
                 late=late + ([run_note] if run_note else []))
        rows.append(r)
    covered = {p.get("rule_log") for p in PREREG} | {n for r in rows for n in r["result_logs"]}
    extra = [n for n in prereg_logs(texts) if n not in covered]
    return rows, extra


def preregistrations(root, entries, texts, files, head):
    rows, extra = prereg_rows(root, entries, texts, files)

    def fixed_s(r):
        return "; ".join(f"{label}: {when(c) if len(c) > 1 else c[0]}" for label, c in r["fixed"]) or "—"

    def res_s(r):
        if r["waiting"]:
            return "waiting"
        return "; ".join(f"{label}: {when(c) if len(c) > 1 else c[0]}" for label, c in r["results"])
    table = [[i + 1, r["track"], ours(r["experiment"]), KINDS[r["kind"]], ours(r["rule"]), fixed_s(r), res_s(r),
              r["before"], ours(r["verdict"]), r["checked"]] for i, r in enumerate(rows)]
    out = ["# Pre-registrations: every rule fixed before its result", "", head, "",
           "One row per rule. **Fixed:** the commit that first added the log stating the rule, or the commit or PLAN "
           "text that holds it (git author dates, MST: −0700). **First result:** the commits that added its FINDINGS "
           "entries and its results log. **Before:** whether the earliest fixing commit precedes the earliest result "
           "commit (calls aren't in git: \"before any call\" rests on the logs). **Checked:** the rule's source and "
           "the results contain the strings this script expects (PREREG in `tools/make_supplement.py`); otherwise "
           "\"unverified\". The verdicts are FINDINGS' and the results logs', in one line.", "",
           "## 1. The ledger", "",
           md_table(["#", "track", "experiment", "kind", "rule", "fixed", "first result", "before", "verdict",
                     "checked"], table), ""]
    notes = [(i + 1, r["note"]) for i, r in enumerate(rows) if r.get("note")]
    notes += [(i + 1, late) for i, r in enumerate(rows) for late in r["late"]]
    if notes:
        out += ["Notes (the times in the logs' names are the session's; the commit times are the evidence):", ""]
        out += [f"- **#{i}:** {ours(n)}" for i, n in sorted(notes)] + [""]
    out += ["## 2. Readings made after the fact, or resting on comparisons named with no decision", "",
            "Each is reported in FINDINGS, but no rule fixed in advance decides it.", ""]
    for i, r in enumerate(rows):
        for a in r.get("after", []):
            out.append(f"- **#{i + 1} {ours(r['experiment'].split(':')[0])}:** {ours(a)}")
    if not any(r.get("after") for r in rows):
        out.append("None.")
    hits = []
    for name, t in [("FINDINGS", (root / FINDINGS_REL).read_text())] + list(texts.items()):
        if name.startswith(("DAILY", "INDEX")):
            continue
        for j, line in enumerate(t.splitlines(), 1):
            if AFTER_WORDS.search(line) and line.strip():
                hits.append([name if name == "FINDINGS" else f"[{name[:-3]}]({LINK}sessions/{name})", j,
                             clean(line, 220)])
    out += ["", "### Every line in FINDINGS and the logs that marks a reading as after the fact, descriptive, "
                "exploratory or with no decision (parsed, unreviewed)", "",
            md_table(["file", "line", "text"], hits) if hits else "None.", "",
            "## 3. Logs that pre-register something, found by the scan but not in the ledger", ""]
    out += [f"- [{n}]({LINK}sessions/{n}): not in PREREG; its rule is unverified here." for n in extra] or ["None."]
    return "\n".join(out) + "\n", {"rows": rows, "extra": extra}


