# ---------------------------------------------------------------- the numbers-only check
def question_starts():
    """The start of every question text available here: export_summaries' (MMLU-Pro, the training pool), the pilot
    puzzles (generated by the code), and C15's items, Track B's cases and set A's items where present."""
    import export_summaries as es
    out = set(es.question_starts())

    def add(q):
        q = (q or "").strip()
        if len(q) >= es.STEM:
            out.add(q[:es.STEM])
    try:
        import experiments as ex
        for it in ex.ITEMS:
            add(it.get("question"))
    except ImportError:
        pass
    for rel in ("results/trackC/c15_items.jsonl", "results/trackB/steered_cases.jsonl",
                "results/trackA/setA/items.jsonl"):
        for row in load(CODE / rel):
            add(row.get("question"))
    return out


def check_outputs(out, starts):
    """{path: [problems]} for every generated file that isn't numbers-only."""
    import export_summaries as es
    bad = {}
    for p in sorted(Path(out).rglob("*")):
        if not p.is_file() or p.suffix == ".png":
            continue
        why = es.problems(p, starts)
        if p.suffix == ".csv":
            lines = [x for x in p.read_text().splitlines() if not x.startswith("# ")]
            long = [v for row in csv.reader(lines) for v in row if len(v) > MAX_CELL]
            if long:
                why.append(f"{len(long)} CSV cells over {MAX_CELL} characters")
        if why:
            bad[p] = why
    return bad


# ---------------------------------------------------------------- build
def build(out, root=REPO):
    """Every supplement file into `out`. Returns ({relative path: rows}, report)."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    head = stamp(root)
    files = tracked_files(root)
    summaries = root / SUM_REL
    texts = session_texts(root)
    entries = findings((root / FINDINGS_REL).read_text())
    counts, report = {}, {}
    md, report["evidence"] = evidence(root, files, head)
    (out / "EVIDENCE.md").write_text(md)
    counts["EVIDENCE.md"] = f"{report['evidence']['entries']} entries, {report['evidence']['numbers']} CLAIMS numbers"
    md, report["prereg"] = preregistrations(root, entries, texts, files, head)
    (out / "PREREGISTRATIONS.md").write_text(md)
    counts["PREREGISTRATIONS.md"] = f"{len(report['prereg']['rows'])} rows"
    md, report["deviations"] = deviations(root, texts, head)
    (out / "DEVIATIONS.md").write_text(md)
    counts["DEVIATIONS.md"] = f"{report['deviations']['curated']} curated, {report['deviations']['hits']} keyword hits"
    md, report["traps"] = traps_md(root, texts, head)
    (out / "TRAPS.md").write_text(md)
    counts["TRAPS.md"] = (f"{report['traps']['traps']} traps + {report['traps']['also']} more, "
                          f"{report['traps']['handoff']} handoff, {report['traps']['log_notes']} log notes")
    t = Tables(out, head)
    tb = table_trackB(t, summaries)
    table_gate3(t, summaries)
    table_setA(t, summaries)
    table_b1(t, summaries)
    tc = table_trackC(t, summaries)
    cue, waiting = table_cues(t, summaries)
    report["waiting"] = waiting
    counts.update(t.counts)
    counts.update(figures(out, summaries, head, tb, tc, cue))
    (out / "APPENDIX_OUTLINE.md").write_text(appendix(root, summaries, head))
    counts["APPENDIX_OUTLINE.md"] = "bullets"
    return counts, report


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="build and check in a scratch folder; write nothing")
    ap.add_argument("--out", help="where to write (default docs/paper/supplement/)")
    a = ap.parse_args(argv)
    with tempfile.TemporaryDirectory(prefix="supplement_") as tmp:
        stage = Path(tmp) / "supplement"
        counts, report = build(stage)
        bad = check_outputs(stage, question_starts())
        for p, why in bad.items():
            print(f"NOT NUMBERS-ONLY: {p.relative_to(stage)}: {'; '.join(why)}")
        if bad:
            print(f"refused: {len(bad)} generated files are not numbers-only; nothing written")
            return False
        for name, n in sorted(counts.items()):
            print(f"{name}: {n}")
        ev = report["evidence"]
        print(f"CLAIMS: {ev['numbers']} numbers, {len(ev['mismatches'])} mismatches, {len(ev['weak'])} weak matches; "
              f"source problems: {len(ev['problems'])}")
        unver = [r["id"] for r in report["prereg"]["rows"] if r["checked"] != "yes"]
        print(f"pre-registrations: {len(report['prereg']['rows'])} rows; unverified: {', '.join(unver) or 'none'}; "
              f"logs outside the ledger: {', '.join(report['prereg']['extra']) or 'none'}")
        for w in report["waiting"]:
            print(w)
        if a.check:
            print("check only: all generated files are numbers-only; nothing written")
            return True
        dest = Path(a.out) if a.out else OUT
        dest.mkdir(parents=True, exist_ok=True)
        shutil.copytree(stage, dest, dirs_exist_ok=True)
        new = {p.relative_to(stage) for p in stage.rglob("*") if p.is_file()}
        stale = sorted(str(p.relative_to(dest)) for p in dest.rglob("*") if p.is_file() and p.relative_to(dest) not in new)
        print(f"wrote {len(new)} files to {dest}" + (f"; not regenerated now (left as they are): {', '.join(stale)}"
                                                      if stale else ""))
        return True


if __name__ == "__main__":
    sys.exit(0 if main() else 1)
