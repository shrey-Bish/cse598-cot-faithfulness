T_HEAD = re.compile(r"^\*\*T(\d+)\. (.+?)\*\*\s*$", re.M)
FIELDS = {"what": "what", "what it does": "what", "found": "found", "the trap": "found", "fix": "fix",
          "source": "source"}


def traps(text):
    """[{n, title, what, found, fix, source, also}] from FINDINGS' traps section, and the 'Also:' bullets."""
    sec = section(text, "Measurement traps")
    heads = list(T_HEAD.finditer(sec))
    also_at = sec.find("**Also:**")
    out = []
    for i, m in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else (also_at if also_at > m.end() else len(sec))
        rec = {"n": int(m.group(1)), "title": m.group(2).rstrip("."), "what": "", "found": "", "fix": "", "source": "",
               "also": []}
        cur = None                     # the field the current bullet's continuation lines belong to
        for line in sec[m.end():end].splitlines():
            b = re.match(r"^- \*([^*]+?)\*\s*(.*)$", line)
            if b:
                label = b.group(1).strip().rstrip(".:")
                cur = FIELDS.get(label.lower(), "also")
                if cur == "also":
                    rec["also"].append(f"{label}: {b.group(2)}")
                else:
                    rec[cur] = (rec[cur] + " " if rec[cur] else "") + b.group(2)
            elif line.strip() and cur == "also":
                rec["also"][-1] += " " + line.strip()
            elif line.strip() and cur:
                rec[cur] += " " + line.strip()
        out.append(rec)
    extra = []
    if also_at >= 0:
        for line in sec[also_at:].splitlines()[1:]:
            if line.startswith("- "):
                extra.append(line[2:].strip())
            elif line.startswith("---") or line.startswith("## "):
                break
            elif line.strip() and extra:
                extra[-1] += " " + line.strip()
    return out, extra


def bullets(sec):
    out = []
    for line in sec.splitlines():
        if line.startswith("- "):
            out.append(line[2:].strip())
        elif line.startswith("  ") and line.strip() and out:
            out[-1] += " " + line.strip()
    return out


def traps_md(root, texts, head):
    ts, extra = traps((root / FINDINGS_REL).read_text())
    out = ["# Measurement traps we hit and fixed", "", head, "",
           f"From [`docs/FINDINGS.md`]({LINK}FINDINGS.md) (\"Measurement traps we hit and fixed\"), the handoffs' "
           "\"Known traps\" and the session logs. Each FINDINGS trap would have changed a reported number.", "",
           "## 1. FINDINGS' traps", ""]
    for t in ts:
        out += [f"### T{t['n']}. {clean(t['title'])}", "", f"- **What:** {clean(t['what']) or '—'}",
                f"- **Found:** {clean(t['found']) or '—'}", f"- **Fix:** {clean(t['fix']) or '—'}",
                f"- **Source:** {clean(t['source']) or '—'}"]
        out += [f"- {clean(a)}" for a in t["also"]] + [""]
    out += ["### Also (FINDINGS, untitled)", ""] + ([f"- {clean(e)}" for e in extra] or ["None."]) + [""]
    out += ["## 2. The handoffs' known traps", ""]
    n_handoff = 0
    for rel in HANDOFFS:
        p = root / rel
        if not p.exists():
            continue
        items = bullets(section(p.read_text(), "6. Known traps"))
        n_handoff += len(items)
        out += [f"### [`{rel}`]({LINK_CODE}{rel})", ""]
        for b in items:
            seen = re.findall(r"\bT(\d+)\b", b)
            out.append(f"- {clean(b)}" + (f" (FINDINGS {', '.join('T' + s for s in seen)})" if seen else ""))
        out.append("")
    notes = []
    for name, t in texts.items():
        if name.startswith(("DAILY", "INDEX")):
            continue
        for j, line in enumerate(t.splitlines(), 1):
            if re.search(r"\btraps?\b", line, re.I):
                notes.append([f"[{name[:-3]}]({LINK}sessions/{name})", j, clean(line, 220)])
    out += ["## 3. Trap notes in the session logs (parsed, unreviewed)", "",
            md_table(["log", "line", "text"], notes) if notes else "None."]
    return "\n".join(out) + "\n", {"traps": len(ts), "also": len(extra), "handoff": n_handoff, "log_notes": len(notes)}


