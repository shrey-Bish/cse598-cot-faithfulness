def mentions(n, texts):
    pat = re.compile(rf"(?<![\w.])F{n}(?![\d_])")
    return [name for name, t in texts.items() if pat.search(t)]


def experiment_map(entries):
    """{'C15': {24}, 'B1': {27}, ...}: experiment ids named in parentheses in the entries' headings."""
    m = defaultdict(set)
    for f in entries:
        for grp in re.findall(r"\(([^)]*)\)", f["title"]):
            for tok in re.findall(r"\b([CB]\d+)\b", grp):
                m[tok].add(f["n"])
    return m


# ---------------------------------------------------------------- CLAIMS: the numbers and the entries they cite
U = r"(?:\d{1,3}(?:,\d{3})+(?![\d,])|\d+(?:\.\d+)?(?:e-?\d+)?)"
S = rf"[+-]?{U}"
ARROW = r" ?(?:->|\u2192) ?"
NUMBER_FORMS = [                     # in priority order; a span taken by an earlier form isn't read again
    ("count with interval", rf"(?<![\w.,-]){U} of {U} \[{U}, {U}%?\]"),
    ("interval", rf"(?<![\w.,]){S}%? ?\[{S}%?, {S}%?\]"),
    ("range of", rf"(?<![\w.,-]){U}-{U} of {U}(?!\d)"),
    ("chain of", rf"(?<![\w.,-])(?<!of ){U}(?:{ARROW}{U})+ of {U}(?!\d)"),
    ("count", rf"(?<![\w.,-]){U} of {U}(?!\d)"),
    ("chain", rf"(?<![\w.,-])(?<!of ){S}%?(?:{ARROW}{S}%?)+"),
    ("percent range", rf"(?<![\w.,-]){U}-{U}%"),
    ("signed", rf"(?<![\w.,\]])[+-]{U}%?(?![\w])"),
    ("percent", rf"(?<![\w.,-]){U}%"),
    ("decimal", r"(?<![\w.,-])0\.\d+"),
]
NUMBER_RES = [(k, re.compile(p)) for k, p in NUMBER_FORMS]
NEAR_OK = {"count with interval", "interval", "count"}     # forms whose numbers may be written otherwise nearby
PARTS_OK = {"chain of", "chain"}      # "6 → 8 of 73" is supported by "6 of 73" and "8 of 73"; a range is not
TOKEN = re.compile(rf"(?<![\w.])[+-]?{U}")


def numbers(text):
    """[(form, string)] in a normalized text, in order: intervals, counts, chains, signed numbers, percents and
    decimals below 1. Bare integers (sizes, dates, layers, model names) are not read."""
    taken, found = [], []
    for kind, rx in NUMBER_RES:
        for m in rx.finditer(text):
            if any(m.start() < b and a < m.end() for a, b in taken):
                continue
            taken.append((m.start(), m.end()))
            found.append((m.start(), kind, m.group(0).strip()))
    return [(k, s) for _, k, s in sorted(found)]


def values(s):
    return [float(t.replace(",", "")) for t in TOKEN.findall(s)]


def tokens(text):
    """[(value, start, end)] of every number in a normalized text (identifiers like Qwen3-8B or L19H31 excluded)."""
    return [(float(m.group(0).replace(",", "")), m.start(), m.end()) for m in TOKEN.finditer(text)]


def _pattern(s):
    return re.compile(r"(?<![\w.,])" + re.escape(s) + r"(?!\d|\.\d)")


def has_seq(seq, text, toks, slack=15, need_of=False):
    """The same numbers in the same order, close together (within len + slack characters); for a count, with "of"
    between the two (e.g. "26 of the 43" for "26 of 43"; "+48 points [+31, +65]" for "+48 [+31, +65]")."""
    k = len(seq)
    width = len(" ".join(f"{v:g}" for v in seq)) + slack + 8 * k
    for i in range(len(toks) - k + 1):
        if [t[0] for t in toks[i:i + k]] == seq and toks[i + k - 1][2] - toks[i][1] <= width:
            if not need_of or re.search(r"\bof\b", text[toks[i][2]:toks[i + 1][1]]):
                return True
    return False


CLAIM_HEAD = re.compile(r"^\*\*(\d+\.\d+)\b")
BULLET = re.compile(r"^(\s*)- (.*)$")
PLACEHOLDER = re.compile(r"\[(?:SOL|TONIGHT):|___")


def claim_units(text):
    """[{claim, line, level, text, parent}]: each claim's title and each bullet with its continuation lines. Sections
    without numbered claims (Supporting) make each top-level bullet a claim, named by its bold label."""
    units, sec, claim, stack, cur, headless = [], None, None, [], None, True
    for i, line in enumerate(text.splitlines(), 1):
        if line.startswith("## "):
            sec, claim, stack, cur, headless = line[3:].strip(), None, [], None, True
            continue
        if sec is None or not line.strip():
            cur = None
            continue
        m = CLAIM_HEAD.match(line)
        if m:
            claim, headless = m.group(1), False
            cur = {"claim": claim, "line": i, "level": -1, "text": line, "parent": None}
            units.append(cur)
            stack = [cur]
            continue
        b = BULLET.match(line)
        if b:
            level = len(b.group(1)) // 2
            if headless and level == 0:
                label = re.match(r"\*\*([^*]+?)\*\*", b.group(2))
                claim = f"{sec.split(' (')[0]}: " + (label.group(1).split(" (")[0].rstrip(":") if label else f"line {i}")
                stack = []
            while stack and stack[-1]["level"] >= level:
                stack.pop()
            cur = {"claim": claim, "line": i, "level": level, "text": b.group(2), "parent": stack[-1] if stack else None}
            units.append(cur)
            stack.append(cur)
            continue
        if cur is not None:
            cur["text"] += " " + line.strip()
    return units


def unit_refs(text, exp):
    out = {int(n) for n in re.findall(r"(?<![\w])F(\d+)(?!\d)", text)}
    for e in re.findall(r"(?<![\w])([CB]\d+)(?!\d)", text):
        out |= exp.get(e, set())
    return out


def check_claims(claims_text, entries, findings_text, log_texts):
    """[{claim, line, form, number, cites, result, where}] for every number in CLAIMS: is it in the entries its bullet
    cites (the bullet's own F-numbers and experiment ids, else its parent's, else the claim's)?"""
    exp = experiment_map(entries)
    by_n = {f["n"]: f for f in entries}
    ntext = {n: norm(f["body"]) for n, f in by_n.items()}
    ntoks = {n: tokens(t) for n, t in ntext.items()}
    nvals = {n: {t[0] for t in ts} for n, ts in ntoks.items()}
    full = norm(findings_text)
    logs = {k: norm(v) for k, v in log_texts.items()}
    units = claim_units(claims_text)
    for u in units:
        u["own"] = unit_refs(u["text"], exp)
    by_claim = defaultdict(set)
    for u in units:
        by_claim[u["claim"]] |= u["own"]
    rows = []
    for u in units:
        if PLACEHOLDER.search(u["text"]):
            continue
        p, cites = u, set()
        while p is not None and not cites:
            cites, p = p["own"], p["parent"]
        cites = sorted(cites or by_claim[u["claim"]])
        for form, s in numbers(norm(u["text"])):
            pat, seq = _pattern(s), values(s)
            of = form in ("count", "count with interval")

            def near(n):
                return form in NEAR_OK and len(seq) > 1 and has_seq(seq, ntext[n], ntoks[n], need_of=of)
            res, where = "not found", []
            if any(pat.search(ntext.get(n, "")) for n in cites):
                res = "exact"
            elif any(near(n) for n in cites if n in ntext):
                res = "format differs"
            else:
                where = [f"F{n}" for n in sorted(ntext) if pat.search(ntext[n]) or near(n)]
                if where:
                    res = "other entry"
                elif pat.search(full):
                    res, where = "FINDINGS, outside the entries", []
                elif form in PARTS_OK and cites and all(any(v in nvals.get(n, ()) for n in cites) for v in seq):
                    res = "by parts"
                else:
                    where = [k for k, t in logs.items() if pat.search(t)][:3]
                    res = "session log only" if where else "not found"
            rows.append({"claim": u["claim"], "line": u["line"], "form": form, "number": display(s, form),
                         "cites": [f"F{n}" for n in cites], "result": res, "where": where})
    return rows


def display(s, form):
    if form in ("range of", "percent range"):
        return s.replace("-", "\u2013")
    return re.sub(r"(?<![\w])-", MINUS, s)


