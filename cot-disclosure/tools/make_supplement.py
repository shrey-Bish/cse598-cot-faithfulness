def findings_history(root, rel=FINDINGS_REL):
    """[(hash, date, {n: normalized entry text})] for every commit that changed FINDINGS, oldest first."""
    rows = [tuple(x.split(",", 1)) for x in git(root, "log", "--reverse", "--format=%h,%ad", "--date=iso", "--",
                                                     rel).splitlines() if "," in x]
    return [(h, d, {f["n"]: norm(f["body"]) for f in findings(git(root, "show", f"{h}:{rel}"))}) for h, d in rows]


def stamp(root):
    head = git(root, "rev-parse", "--short", "HEAD").strip() or "no commit"
    dirty = git(root, "status", "--porcelain", "--", "docs", f"{SUM_REL}", "cot-disclosure/configs",
                ":(exclude)docs/paper/supplement").strip()
    line = f"Generated by tools/make_supplement.py on {date.today().isoformat()} from {head}; do not edit by hand."
    return line + (" Some of its inputs had uncommitted changes at the time." if dirty else "")


# ---------------------------------------------------------------- text
_TRANS = str.maketrans({MINUS: "-", "\u2013": "-", "\u2009": " ", "\u00a0": " ", "\u202f": " "})
QUOTED = re.compile(r"\"[^\"\n]*\"|\u201c[^\u201d\n]*\u201d")


def norm(s):
    """For matching: the Unicode minus and en dash as '-', no emphasis or code marks, single spaces."""
    return re.sub(r"\s+", " ", re.sub(r"[*`]", "", (s or "").translate(_TRANS))).strip()


def clean(s, limit=None, quotes=True):
    """A line copied from the docs: single spaces, every quote of QUOTE_MIN or more characters as "[quote]" (it may be
    model output; quotes=False for text written in this file), cut at `limit` characters."""
    s = re.sub(r"\s+", " ", re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s or "")).strip()   # a link's target is relative
    if quotes:                                                                             # to the file it came from
        s = QUOTED.sub(lambda m: m.group(0) if len(m.group(0)) - 2 < QUOTE_MIN else '"[quote]"', s)
    return s[:limit - 1].rstrip() + "\u2026" if limit and len(s) > limit else s


def source_link(path):
    """A source path as a link from the supplement; a glob (figures/gate3_*) as code: it names several files."""
    return f"`{path}`" if "*" in path else f"[`{path}`]({LINK_CODE}{path})"


def ours(s):
    """Text written in this file (the curated tables): single spaces, quotes kept."""
    return clean(s, quotes=False)


def cell(x):
    return ("" if x is None else str(x)).replace("|", "\\|").replace("\n", " ")


def md_table(cols, rows):
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    return "\n".join(out + ["| " + " | ".join(cell(v) for v in r) + " |" for r in rows])


def sgn(x, nd=0):
    """'+5' / '−5' in FINDINGS' style; 0 is '+0'."""
    s = f"{x:+.{nd}f}"
    return ("+" + s[1:] if float(s) == 0 else s).replace("-", MINUS)


def pts(d, iv, nd=0, scale=100):
    """A difference in points with its interval: '−21 [−34, −8]'; 'too few questions' without an interval."""
    if d is None:
        return "—"
    if not iv or iv[0] is None:
        return f"{sgn(d * scale, nd)} (too few questions)"
    return f"{sgn(d * scale, nd)} [{sgn(iv[0] * scale, nd)}, {sgn(iv[1] * scale, nd)}]"


def share(m, lo, hi, nd=2):
    if m is None:
        return "—"
    if lo is None:
        return f"{m:.{nd}f} (too few questions)"
    return f"{m:.{nd}f} [{lo:.{nd}f}, {hi:.{nd}f}]".replace("-", MINUS)


def kof(k, n, wil=False):
    if n is None:
        return "—"
    if not wil or not n:
        return f"{k} of {n}"
    lo, hi = wilson(k, n)
    return f"{k} of {n} [{lo * 100:.0f}, {hi * 100:.0f}%]"


def rnd(x, nd=6):
    return None if x is None else round(x, nd)


# ---------------------------------------------------------------- FINDINGS
F_HEAD = re.compile(r"^## F(\d+)\. (.+)$")


def findings(text):
    """[{n, title, body, line}] in file order; an entry runs from its heading to the next '## ' heading."""
    heads = list(re.finditer(r"^## .*$", text, re.M))
    out = []
    for i, m in enumerate(heads):
        f = F_HEAD.match(m.group(0))
        if f:
            end = heads[i + 1].start() if i + 1 < len(heads) else len(text)
            out.append({"n": int(f.group(1)), "title": f.group(2).strip(), "body": text[m.start():end],
                        "line": text.count("\n", 0, m.start()) + 1})
    return out


def section(text, title_start):
    """The text of the '## ' section whose title starts with title_start ('' if none)."""
    m = re.search(rf"^## {re.escape(title_start)}.*$", text, re.M)
    if not m:
        return ""
    nxt = re.search(r"^## ", text[m.end():], re.M)
    return text[m.start(): m.end() + (nxt.start() if nxt else len(text))]


SRC_END = re.compile(r"\n[ \t]*\n|\n[ \t]*(?:- )?\*\*(?!Source)[A-Z][^*\n]{0,80}?[.:]\*\*")
PATH_EXT = (".json", ".jsonl", ".png", ".svg", ".csv", ".md", ".npz", ".gz", ".txt", ".py", ".yaml")
CODE_DIRS = ("results/", "finetune/", "agents/", "progress/", "tools/", "configs/", "data/", "providers/")


def source_text(body):
    """An entry's Source paragraph: from '**Source.**' (or '**Source:**') to the next blank line or bold label ('' if
    none)."""
    m0 = re.search(r"\*\*Source[.:]\*\*", body)
    if not m0:
        return ""
    i = m0.start()
    m = SRC_END.search(body[i:], 1)
    return body[i:i + m.start()] if m else body[i:]


def code_spans(text):
    return [re.sub(r"\s+", " ", s).strip() for s in re.findall(r"`([^`]+)`", re.sub(r"\s+", " ", text))]


def resolve(s, context, files, root):
    """{given, path, status, also}: where a file named in a Source paragraph is. A bare name is looked up next to the
    last file named before it, then among the tracked summaries (the shallowest match; others listed in `also`)."""
    s = s.rstrip(",;:")
    if s.startswith(("cot-disclosure/", "docs/", "presentation/")):
        cands = [s]
    elif s.startswith(CODE_DIRS):
        cands = ["cot-disclosure/" + s]
    elif s.endswith(".py"):           # a module named bare: in cot-disclosure/, else wherever it is tracked
        cands = [p for p in [f"cot-disclosure/{s}"] if p in files] or sorted(
            (p for p in files if p.endswith("/" + s)), key=lambda p: (p.count("/"), p)) or [f"cot-disclosure/{s}"]
    else:
        near = f"{context}/{s}" if context else None
        if near and (near in files or (root / near).exists() or ("*" in s and fnmatch.filter(files, near))):
            cands = [near]
        else:
            cands = sorted((p for p in files if p.startswith(SUM_REL + "/") and p.endswith("/" + s)),
                           key=lambda p: (p.count("/"), p)) or [near or f"{SUM_REL}/{s}"]
    path, also = cands[0], cands[1:]
    if "*" in path:
        hits = fnmatch.filter(sorted(files), path)
        status = f"tracked ({len(hits)} files)" if hits else "missing"
    elif path in files:
        status = "tracked"
    elif (root / path).exists():
        status = "on disk, not tracked"
    elif git_ok(root, "cat-file", "-e", f"main:{path}"):
        status = "on main only"
    else:
        status = "missing"
    return {"given": s, "path": path, "status": status, "also": also}


def sources(entry, files, root):
    """{summaries, others, commands, extra_commands} named in an entry's Source paragraph."""
    src = source_text(entry["body"])
    out = {"summaries": [], "others": [], "commands": [], "extra_commands": []}
    context, last = None, None
    for s in code_spans(src):
        if re.fullmatch(r"\.\w+", s) and last:          # "(+ `.png`)": the file named before, another suffix
            s = last.rsplit(".", 1)[0] + s
        if s.startswith("python "):
            script = s.split()[1] if len(s.split()) > 1 else ""
            out["commands"].append({"command": s, "script": script,
                                    "script_tracked": f"cot-disclosure/{script}" in files})
        elif " " not in s and (s.lower().endswith(PATH_EXT) or ("*" in s and "/" in s)):
            r = resolve(s, context, files, root)
            if r["status"] != "missing" and "*" not in r["path"] and not r["path"].endswith(".py"):
                context, last = r["path"].rsplit("/", 1)[0], r["path"]
            out["summaries" if r["path"].startswith(SUM_REL + "/") else "others"].append(r)
    if not out["commands"]:          # a command elsewhere in the entry, reported as such
        out["extra_commands"] = [s for s in code_spans(entry["body"]) if s.startswith("python ")]
    return out


