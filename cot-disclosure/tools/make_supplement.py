class Tables:
    """Writes each table as tables/<name>.md and .csv (both with the header line) and keeps the row counts."""

    def __init__(self, out, head):
        self.dir, self.head, self.counts, self.missing = Path(out) / "tables", head, {}, []
        self.dir.mkdir(parents=True, exist_ok=True)

    def write(self, name, title, intro, md_cols, md_rows, csv_rows, notes=()):
        (self.dir / f"{name}.md").write_text("\n".join(
            [f"# {title}", "", self.head, "", intro, "", md_table(md_cols, md_rows), ""]
            + [f"- {n}" for n in notes] + ([""] if notes else [])))
        with open(self.dir / f"{name}.csv", "w", newline="") as f:
            f.write(f"# {self.head}\n")
            cols = list(dict.fromkeys(k for r in csv_rows for k in r)) if csv_rows else ["note"]
            w = csv.DictWriter(f, fieldnames=cols)
            w.writeheader()
            w.writerows(csv_rows or [{"note": "no rows"}])
        self.counts[f"tables/{name}.md"] = len(md_rows)
        self.counts[f"tables/{name}.csv"] = len(csv_rows)


