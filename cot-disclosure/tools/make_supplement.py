def pair_k(e):
    """(k_a, n_a, k_b, n_b) of a comparison entry, whatever its key names."""
    for a, b in (("variant", "answer_only"), ("added", "original"), ("final", "own"), ("c16", "c15")):
        if f"{a}_k" in e:
            return e[f"{a}_k"], e[f"{a}_n"], e[f"{b}_k"], e[f"{b}_n"]
    return None, None, None, None


def c11_rule(e):
    if not e or e.get("diff") is None:
        return ""
    lo, hi = e["interval"]
    if hi < -MARGIN:
        return "defers"
    if lo <= 0 <= hi or lo > -MARGIN:
        return "doesn't defer"
    return "unclear"


