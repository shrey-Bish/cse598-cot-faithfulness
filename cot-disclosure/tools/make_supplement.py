def stamp_files(paths, head):
    """The header line in each figure file: a CSV comment line, an SVG comment, a PNG text chunk."""
    for p in map(Path, paths):
        if p.suffix == ".csv":
            p.write_text(f"# {head}\n" + p.read_text())
        elif p.suffix == ".svg":
            t = p.read_text()
            i = t.find("?>") + 2 if t.startswith("<?xml") else 0
            p.write_text(t[:i] + f"\n<!-- {head} -->" + t[i:])
        elif p.suffix == ".png":
            try:
                from PIL import Image
                from PIL.PngImagePlugin import PngInfo
                im = Image.open(p)
                info = PngInfo()
                info.add_text("Description", head)
                im.load()
                im.save(p, pnginfo=info, dpi=im.info.get("dpi", (200, 200)))
            except ImportError:
                pass


