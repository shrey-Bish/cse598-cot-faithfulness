def evidence(root, files, head):
    text = (root / FINDINGS_REL).read_text()
    entries = findings(text)
    logs = session_texts(root)
    commits = heading_commits(root)
    claims_path = root / CLAIMS_REL
    checks = check_claims(claims_path.read_text(), entries, text, logs) if claims_path.exists() else []
