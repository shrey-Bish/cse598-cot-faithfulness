"""docs/GLOSSARY.md, written from tools/explainer/names.json (plain name -> internal IDs -> what). No dates, no
randomness: the same names.json gives the same bytes.

  python tools/make_glossary.py          # -> docs/GLOSSARY.md
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NAMES = ROOT / "cot-disclosure" / "tools" / "explainer" / "names.json"
OUT = ROOT / "docs" / "GLOSSARY.md"


def _cell(s):
    return str(s).replace("|", "\\|")


def render(names_path=NAMES):
    data = json.loads(Path(names_path).read_text())
    lines = [
        "# Glossary: plain names and the internal codes behind them",
        "",
        "*Generated by `cot-disclosure/tools/make_glossary.py` from `cot-disclosure/tools/explainer/names.json`. "
        "Do not edit by hand: change names.json and rerun the script.*",
        "",
        "The README, the Hint Explainer and the slide figures use the plain names. FINDINGS, the session logs and "
        "the pre-registrations keep the internal codes, because they are the research record. Use this table to go "
        "from one to the other: find the plain name, and its codes (A40, F41, B1R2 and so on) are the ones to search "
        "for in those files.",
        "",
    ]
    for g in data["groups"]:
        lines += ["## " + g["group"], "", "| Plain name | Internal codes | What it is |", "|---|---|---|"]
        for n in g["names"]:
            ids = ", ".join("`" + _cell(i) + "`" for i in n["ids"])
            lines.append("| %s | %s | %s |" % (_cell(n["plain"]), ids, _cell(n["what"])))
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    OUT.write_text(render())
    print("wrote", OUT)


if __name__ == "__main__":
    main()
