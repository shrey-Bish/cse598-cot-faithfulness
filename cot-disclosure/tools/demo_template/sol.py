"""The demo's targeted copy from Sol (Nov 22): only the drawn runs, the training logs and a GPU-hour total, read-only.

  python tools/demo_template/sol.py plan      # -> results/demo/sol/plan.json and fetch_remote.py (gitignored)
  # then, from the ASU network (one Duo push), Ritik runs the one command printed by `plan`:
  #   ssh ... '<python> -I -S -' < results/demo/sol/fetch_remote.py | python3 tools/demo_template/sol.py unpack results/demo/sol
  python tools/demo_template/sol.py unpack DIR   # reads the stream on stdin, writes DIR/ (runs_*.jsonl, train/, sacct.json)

The remote script is stdlib-only and only reads (the pattern of tools/l6_sheet.py --remote-script): it globs the paths in
docs/demo/INVENTORY.md section 4 under /scratch/$USER, keeps the records of the drawn questions (draw.json) whose run id
is in this Mac's numbers-only run index (Nemotron has no index here: its drawn questions' records are kept), and prints
JSON lines: each kept record with its file and line, every train_log.jsonl and chosen.json under trackA/train/, and
sacct's jobs since Oct 1 with their GPU hours. Paths in the output say <scratch>, never the account name. Nothing is
written on Sol. Gemma and Granite (Arsha's account) are not fetched.
"""
import glob
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CODE = HERE.parents[1]
RES = CODE / "results"
SOL_DIR = RES / "demo" / "sol"
REPO_B = "/cse598-cot-faithfulness/cot-disclosure/results/trackB"
COMMAND = ("cd ~/Documents/Projects/ODL/cse598-cot-faithfulness/cot-disclosure && "
           "ssh -o ConnectTimeout=30 login.sol.rc.asu.edu "
           "'P=/scratch/$USER/envs/olmo/bin/python; [ -x $P ] || P=python3; $P -I -S -' "
           "< results/demo/sol/fetch_remote.py | python3 tools/demo_template/sol.py unpack results/demo/sol")


def _jsonl(p):
    with open(p) as f:
        return [json.loads(x) for x in f if x.strip()]


def plan(res=RES, draw_path=HERE / "draw.json"):
    d = json.loads(Path(draw_path).read_text())["sets"]
    t54, f120, h30 = set(d["test54"]["drawn"]), set(d["fresh120"]["drawn"]), set(d["held30"]["drawn"])

    def ids(files, items, keep=lambda r: True):
        out = set()
        for p in files:
            for r in _jsonl(p):
                if r.get("item_id") in items and r.get("run_id") and keep(r):
                    out.add(r["run_id"])
        return sorted(out)

    a39 = sorted(glob.glob(str(res / "trackA/gpu/a39/eval_*_runs.jsonl")))
    groups = [
        {"group": "fixes_120", "items": sorted(f120), "globs": ["/trackA/a39/eval_*_a39_e2_p*.jsonl.gz"],
         "run_ids": ids([p for p in a39 if "_a39_e2_" in p], f120)},
        {"group": "fixes_30", "items": sorted(h30), "globs": ["/trackA/a39/eval_*_a39_mmlupro_30_p*.jsonl.gz", "/trackA/eval/eval_*.jsonl.gz"],
         "run_ids": ids([p for p in a39 if "_a39_mmlupro_30_" in p] + sorted(glob.glob(str(res / "trackA/gpu/eval/eval_*_runs.jsonl"))), h30)},
        {"group": "qwen8b", "items": sorted(t54), "globs": [REPO_B + "/sol_vllm*.jsonl.gz"],
         "run_ids": ids([res / "trackB/sol_vllm_runs.jsonl"], t54)},
        {"group": "gptoss", "items": sorted(t54), "globs": [REPO_B + "/b17/*.jsonl.gz", REPO_B + "/b17_*.jsonl.gz"],
         "run_ids": ids([res / "trackB/b17_sol_vllm_runs.jsonl"], t54)},
        {"group": "nemotron", "items": sorted(t54), "globs": [REPO_B + "/b20/nemotron-3-nano-30b-a3b/*.jsonl.gz"], "run_ids": None},
    ]
    return {"since": "2026-10-01", "groups": groups,
            "train": ["/trackA/train/*/train_log.jsonl", "/trackA/train/*/chosen.json"],
            "list": ["/trackA/a39/eval_*.jsonl.gz", "/trackA/eval/eval_*.jsonl.gz", "/trackA/train/*", REPO_B + "/*.jsonl.gz",
                     REPO_B + "/b17/*", REPO_B + "/b20/*/*"]}


REMOTE = r'''# Read-only, stdlib only: the demo's targeted copy (generated by tools/demo_template/sol.py plan). Writes nothing.
import glob, gzip, json, os, re, subprocess, sys, time
PLAN = json.loads(__PLAN__)
S = os.environ.get("DEMO_SOL_ROOT") or "/scratch/" + os.environ.get("USER", "")
def out(o): sys.stdout.write(json.dumps(o, ensure_ascii=False) + "\n")
def rel(p): return "<scratch>" + p[len(S):] if p.startswith(S) else p
out({"kind": "start", "utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())})
for pat in PLAN["list"]:
    for p in sorted(glob.glob(S + pat)):
        try: out({"kind": "file", "path": rel(p), "bytes": os.path.getsize(p)})
        except OSError: pass
for g in PLAN["groups"]:
    items, want = set(g["items"]), (set(g["run_ids"]) if g["run_ids"] is not None else None)
    for pat in g["globs"]:
        for p in sorted(glob.glob(S + pat)):
            kept = skipped = 0
            try:
                with gzip.open(p, "rt", encoding="utf-8") as f:
                    for i, line in enumerate(f, 1):
                        if not any(it in line for it in items): continue
                        r = json.loads(line)
                        if r.get("item_id") not in items: continue
                        if want is not None and r.get("run_id") not in want:
                            skipped += 1; continue
                        if r.get("reasoning_text") is not None and r.get("final_text") is not None: r.pop("raw_text", None)
                        out({"kind": "run", "group": g["group"], "src": rel(p), "line": i, "record": r}); kept += 1
            except Exception as e:
                out({"kind": "error", "src": rel(p), "error": repr(e)[:300]})
            out({"kind": "scanned", "group": g["group"], "src": rel(p), "kept": kept, "not_in_index": skipped})
for pat in PLAN["train"]:
    for p in sorted(glob.glob(S + pat)):
        v = p.split("/")[-2]
        try:
            if p.endswith(".jsonl"):
                with open(p) as f: out({"kind": "train_log", "version": v, "src": rel(p), "lines": [json.loads(x) for x in f if x.strip()]})
            else:
                with open(p) as f: out({"kind": "chosen", "version": v, "src": rel(p), "value": json.load(f)})
        except Exception as e:
            out({"kind": "error", "src": rel(p), "error": repr(e)[:300]})
fmt = "JobID,JobName%60,Partition,State,ElapsedRaw,AllocTRES,Start,End"
try:
    sa = subprocess.run(["sacct", "-u", os.environ.get("USER", ""), "-S", PLAN["since"], "-E", "now", "-X", "-P", "-n",
                         "--format=" + fmt], stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True, timeout=300)
    rows = []
    for line in sa.stdout.splitlines():
        f = line.split("|")
        if len(f) < 8: continue
        tres = f[5]
        m = re.search(r"gres/gpu=(\d+)", tres) or re.search(r"gres/gpu:[^=,]+=(\d+)", tres)
        gpus = int(m.group(1)) if m else 0
        secs = int(f[4]) if f[4].isdigit() else 0
        rows.append({"job": f[0], "name": f[1], "partition": f[2], "state": f[3], "seconds": secs, "gpus": gpus,
                     "gpu_hours": round(secs * gpus / 3600.0, 3), "start": f[6], "end": f[7]})
    out({"kind": "sacct", "since": PLAN["since"], "format": fmt, "rows": rows, "stderr": sa.stderr[-500:]})
except Exception as e:
    out({"kind": "error", "src": "sacct", "error": repr(e)[:300]})
out({"kind": "end", "utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())})
'''


def remote_script(p):
    return REMOTE.replace("__PLAN__", repr(json.dumps(p)))


def unpack(stream, out_dir):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    runs, train, chosen, files, errors, scanned, sacct = {}, {}, {}, [], [], [], None
    for line in stream:
        if not line.strip():
            continue
        o = json.loads(line)
        k = o.get("kind")
        if k == "run":
            runs.setdefault(o["group"], []).append({"src": o["src"], "line": o["line"], "record": o["record"]})
        elif k == "train_log":
            train[o["version"]] = o
        elif k == "chosen":
            chosen[o["version"]] = o
        elif k == "file":
            files.append(o)
        elif k == "scanned":
            scanned.append(o)
        elif k == "error":
            errors.append(o)
        elif k == "sacct":
            sacct = o
    for g, rows in runs.items():
        with open(out_dir / f"runs_{g}.jsonl", "w") as f:
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
    for v, o in train.items():
        (out_dir / "train" / v).mkdir(parents=True, exist_ok=True)
        with open(out_dir / "train" / v / "train_log.jsonl", "w") as f:
            for x in o["lines"]:
                f.write(json.dumps(x) + "\n")
    for v, o in chosen.items():
        (out_dir / "train" / v).mkdir(parents=True, exist_ok=True)
        (out_dir / "train" / v / "chosen.json").write_text(json.dumps(o["value"], indent=1) + "\n")
    if sacct is not None:
        rows = sacct["rows"]
        by = {}
        for r in rows:
            by[r["name"]] = round(by.get(r["name"], 0) + r["gpu_hours"], 3)
        summary = {"since": sacct["since"], "jobs": len(rows), "gpu_jobs": sum(1 for r in rows if r["gpus"]),
                   "gpu_hours": round(sum(r["gpu_hours"] for r in rows), 2), "by_name": by, "rows": rows,
                   "account": "Ritik's own Sol account"}
        (out_dir / "sacct.json").write_text(json.dumps(summary, indent=1) + "\n")
    manifest = {"runs": {g: len(r) for g, r in runs.items()}, "train_logs": sorted(train), "chosen": sorted(chosen),
                "sacct_jobs": len(sacct["rows"]) if sacct else None, "files_listed": files, "scanned": scanned, "errors": errors}
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    print("runs:", manifest["runs"], "| train logs:", len(train), "| chosen:", len(chosen),
          "| sacct jobs:", manifest["sacct_jobs"], "| errors:", len(errors))
    return manifest


def main(argv):
    if argv and argv[0] == "plan":
        p = plan()
        SOL_DIR.mkdir(parents=True, exist_ok=True)
        (SOL_DIR / "plan.json").write_text(json.dumps(p, indent=1) + "\n")
        (SOL_DIR / "fetch_remote.py").write_text(remote_script(p))
        print({g["group"]: (len(g["items"]), None if g["run_ids"] is None else len(g["run_ids"])) for g in p["groups"]})
        print(COMMAND)
    elif argv and argv[0] == "unpack":
        unpack(sys.stdin, argv[1] if len(argv) > 1 else SOL_DIR)
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
